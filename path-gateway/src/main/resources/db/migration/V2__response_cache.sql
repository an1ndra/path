-- Exact-match response cache (issue #10).
-- Opt-in per route; only deterministic requests (temperature 0, no tools) are stored.

alter table model_routes add column cache_enabled boolean not null default false;
alter table model_routes add column cache_ttl_seconds integer not null default 3600;

create table response_cache_entries (
    id bigint generated by default as identity,
    cache_key varchar(64) not null unique,
    client_key_id bigint not null,
    public_model_id varchar(128),
    provider_slug varchar(64),
    content_type varchar(128),
    body text,
    prompt_tokens integer not null,
    completion_tokens integer not null,
    total_tokens integer not null,
    cost_usd numeric(18,8),
    created_at timestamp(6) with time zone not null,
    expires_at timestamp(6) with time zone not null,
    primary key (id)
);

create index ix_cache_expiry on response_cache_entries (expires_at);
