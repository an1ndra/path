-- Operator-defined model aliases (issue #68). The capability aliases (cheap, fast,
-- long-context, vision) stay computed; these are stable chains a product can depend on.

create table model_aliases (
    id bigint generated by default as identity,
    alias varchar(80) not null unique,
    models varchar(1000) not null,
    description varchar(400),
    created_at timestamp(6) with time zone not null,
    primary key (id)
);
