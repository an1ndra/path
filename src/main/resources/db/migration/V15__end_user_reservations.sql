-- Reserve end-user budget the way key credit is reserved (issue #64), so concurrent
-- requests for one end user cannot overshoot the cap between the check and the charge.

create table end_user_reservations (
    id bigint generated by default as identity,
    client_key_id bigint not null,
    end_user varchar(128) not null,
    reserved_usd numeric(18,6) not null default 0,
    updated_at timestamp(6) with time zone,
    primary key (id),
    constraint uk_end_user_reservation unique (client_key_id, end_user)
);
